# Write a program that takes two numbers as input, stores them in variables first_number and second_number, then prints their sum, difference, and product.

first_number=int(input("Enter First Number:"))
second_number=int(input("Enter Second Number:"))

print(f"Sum of {first_number} and {second_number} is {first_number+second_number}")
print(f"Difference of {first_number} and {second_number} is {first_number-second_number}")
print(f"Product of {first_number} and {second_number} is {first_number*second_number}")